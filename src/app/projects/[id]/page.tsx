function formatReviewStatus(value?: string | null) {
  if (!value || value === "not_requested") return "No review started";
  return value.replace(/_/g, " ");
}

function checkpointTone(value?: string | null) {
  switch (value) {
    case "approved":
      return "border-emerald-200 bg-emerald-50 text-emerald-700";
    case "pending":
    case "ready_for_review":
      return "border-accent/16 bg-accent-soft/80 text-accent-soft-foreground";
    case "rejected":
    case "changes_requested":
      return "border-red-200 bg-red-50 text-red-700";
    case "awaiting_evidence":
    case "setup_required":
      return "border-amber-200 bg-amber-50 text-amber-700";
    default:
      return "border-border bg-panel-elevated text-text-secondary";
  }
}

function isPrebuildCheckpointMilestone(milestone: Milestone) {
  const checkpointType = milestone.reviewSummary?.checkpointType || milestone.checkpointType;
  return checkpointType === "prebuild_checkpoint";
}

function isBlockerOnlyCheckpoint(milestone: Milestone) {
  return isPrebuildCheckpointMilestone(milestone)
    && milestone.preBuildCheckpoint?.outcome != null
    && milestone.preBuildCheckpoint.outcome !== "match"
    && !milestone.reviewRequest;
}

function formatCheckpointReason(reason?: string | null) {
  if (!reason) return null;

  return reason
    .replace(/^Manual review required for unsupported requirement kinds:\s*/i, "Needs manual review because these requirement types could not be auto-checked: ")
    .replace(/^Missing required project artifact:\s*/i, "Missing required project artifact: ")
    .replace(/^Code-heavy delivery cannot advance to review or completion without a real GitHub repo linked to the project\.?/i, "Add a real GitHub repo to this project before this work can be approved.")
    .replace(/^GitHub repo provisioning is in progress for this code-heavy project\. A real repo will still be required before review or completion\.?/i, "GitHub repo setup is still in progress. This work stays blocked until a real repo is linked.");
}

function formatTaskStatusLabel(value?: string | null) {
  if (!value) return "Unknown";
  return value.replace(/_/g, " ");
}

function isStaleSystemTaskCopy(value?: string | null) {
  if (!value) return false;
  return /bootstrap is still pending|\bi read bootstrap\.md\b|identity\/preferences answers|delivery review\s*:\s*iteration shipped/i.test(value);
}

function getTaskCardSummary(task: any, blocker?: { label?: string | null; detail?: string | null; resolution?: string | null } | null) {
  if (blocker?.detail) {
    return blocker.detail;
  }

  if (task?.description && !isStaleSystemTaskCopy(task.description)) {
    return task.description;
  }

  if (typeof task?.task_goal === "string" && task.task_goal.trim()) {
    if (task.status === "blocked") {
      return `This work is blocked before ${task.task_goal.trim()} can move forward.`;
    }
    return task.task_goal.trim();
  }

  return null;
}

function taskProgressValue(task: any) {
  if (!task) return null;

  if (task.status === "done" || task.status === "completed") {
    return 100;
  }

  if (typeof task?.progress_pct === "number" && Number.isFinite(task.progress_pct)) {
    return Math.max(0, Math.min(100, task.progress_pct));
  }

  return null;
}

function isBootstrapTask(task: any, bootstrapSprintIds?: ReadonlySet<string>) {
  return matchesBootstrapTruth(task, bootstrapSprintIds);
}

function formatBytes(value?: number | null) {
  if (!value) return null;
  if (value < 1024) return `${value} B`;
  if (value < 1024 * 1024) return `${Math.round(value / 1024)} KB`;
  return `${(value / (1024 * 1024)).toFixed(1)} MB`;
}

function artifactEmptyState(projectType?: string | null, intake?: any) {
  if (intake?.shape === "launch-campaign" || ["marketing_growth", "marketing"].includes(projectType || "")) {
    return "No campaign links or creative artifacts added yet.";
  }
  if (["product_build", "ops_enablement", "saas", "web_app", "native_app"].includes(projectType || "")) {
    return "No repo, environment, or build links added yet.";
  }
  return "No project links or artifacts added yet.";
}

